#!/usr/bin/env python3
"""Generate the Photo·AIrt icon: SVG sources, the Linux icon theme, the Windows .ico and the macOS .icns.

The design is a photo frame whose sun is the AI sparkle, with a brush stroke in the
app's pigments breaking out of it. A bolder "small cut" (no hills, a bigger sparkle)
is used at 32 px and below, where the full design would blur.

Run from anywhere after editing the design; needs Python 3 and `rsvg-convert`
(librsvg). The outputs are committed, so builds never need these tools:

    python3 assets/icon/build.py
"""

import math
import pathlib
import struct
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICON = ROOT / "assets" / "icon"
HICOLOR = ROOT / "packaging" / "linux" / "share" / "icons" / "hicolor"

GOLD = "#e3b15c"
CLAUDE = "#d97757"
CODEX = "#3fbeac"
DUET = "#b48cff"
CREAM = "#ece6da"
WINDOW = "#1d1a22"

DEFS = f"""  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#2a2530"/><stop offset="1" stop-color="#0e0d11"/>
    </linearGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{GOLD}" stop-opacity="0.55"/><stop offset="1" stop-color="{GOLD}" stop-opacity="0.08"/>
    </linearGradient>
    <linearGradient id="stroke" x1="0" y1="1" x2="1" y2="0">
      <stop offset="0" stop-color="{CODEX}"/><stop offset="0.5" stop-color="{DUET}"/><stop offset="1" stop-color="{CLAUDE}"/>
    </linearGradient>
    <radialGradient id="glow">
      <stop offset="0" stop-color="{GOLD}" stop-opacity="0.55"/><stop offset="1" stop-color="{GOLD}" stop-opacity="0"/>
    </radialGradient>
    <clipPath id="window"><rect x="262" y="262" width="500" height="500" rx="36"/></clipPath>
  </defs>"""

# The rounded tile behind the app icon; 100 px margins on a 1024 canvas, as macOS expects.
TILE = """  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg)"/>
  <rect x="104" y="104" width="816" height="816" rx="181" fill="none" stroke="url(#rim)" stroke-width="8"/>"""


def sparkle(cx, cy, r, fill, waist):
    """A four-pointed star with concave sides: the AI sparkle."""
    pts = []
    for i in range(8):
        a = -math.pi / 2 + i * math.pi / 4
        rr = r if i % 2 == 0 else r * waist
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    d = f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    for i in range(1, 9):
        p, prev = pts[i % 8], pts[i - 1]
        c = ((prev[0] + p[0]) / 2 * 0.6 + cx * 0.4, (prev[1] + p[1]) / 2 * 0.6 + cy * 0.4)
        d += f" Q{c[0]:.1f},{c[1]:.1f} {p[0]:.1f},{p[1]:.1f}"
    return f'<path d="{d} Z" fill="{fill}"/>'


FULL = f"""  <rect x="262" y="262" width="500" height="500" rx="36" fill="{WINDOW}"/>
  <g clip-path="url(#window)">
    <circle cx="560" cy="395" r="115" fill="url(#glow)"/>
    {sparkle(560, 395, 100, GOLD, 0.3)}
    <path d="M262,690 L420,500 L520,610 L590,540 L762,720 L762,762 L262,762 Z" fill="{CREAM}" fill-opacity="0.18"/>
  </g>
  <rect x="262" y="262" width="500" height="500" rx="36" fill="none" stroke="{CREAM}" stroke-width="30"/>
  <path d="M205,792 C330,690 470,640 600,520 C690,437 760,330 836,236 C820,330 760,470 660,575 C540,700 380,770 205,792 Z" fill="url(#stroke)"/>
  <path d="M232,780 C380,720 520,650 640,520" fill="none" stroke="#fff" stroke-opacity="0.28" stroke-width="10" stroke-linecap="round"/>"""

SMALL = f"""  <rect x="250" y="250" width="524" height="524" rx="60" fill="{WINDOW}"/>
  <rect x="250" y="250" width="524" height="524" rx="60" fill="none" stroke="{CREAM}" stroke-width="56"/>
  {sparkle(462, 440, 185, GOLD, 0.42)}
  <path d="M180,830 C330,700 470,650 600,540 C700,455 770,350 850,220 C840,350 780,500 680,600 C550,730 390,810 180,830 Z" fill="url(#stroke)"/>"""


# Views of the 1024 canvas: macOS icons keep a 100 px margin around the tile,
# Linux and Windows icons fill their square, and the mark is cropped to the art.
MACOS, SQUARE, MARK = "0 0 1024 1024", "92 92 840 840", "180 180 664 664"


def svg(art, view):
    body = art if view == MARK else f"{TILE}\n{art}"
    note = "<!-- Generated by assets/icon/build.py; edit that script, not this file. -->"
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}">\n  {note}\n{DEFS}\n{body}\n</svg>\n'


def render(text, size):
    return subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size)], input=text.encode(), check=True, capture_output=True).stdout


def ico(images):
    """A Windows .ico whose entries are PNGs (supported since Windows Vista)."""
    head = struct.pack("<HHH", 0, 1, len(images))
    offset = len(head) + 16 * len(images)
    entries, data = b"", b""
    for size, png in images:
        dim = 0 if size >= 256 else size
        entries += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(png), offset + len(data))
        data += png
    return head + entries + data


def icns(chunks):
    """A macOS .icns of PNG chunks."""
    body = b"".join(kind + struct.pack(">I", 8 + len(png)) + png for kind, png in chunks)
    return b"icns" + struct.pack(">I", 8 + len(body)) + body


def main():
    sources = {
        "photo-airt.svg": svg(FULL, SQUARE),
        "photo-airt-small.svg": svg(SMALL, SQUARE),
        "photo-airt-macos.svg": svg(FULL, MACOS),
        "mark.svg": svg(FULL, MARK),
        "mark-small.svg": svg(SMALL, MARK),
    }
    for name, text in sources.items():
        (ICON / name).write_text(text)

    def pick(size, macos=False):
        if macos:
            return render(svg(SMALL, MACOS) if size <= 32 else sources["photo-airt-macos.svg"], size)
        return render(sources["photo-airt-small.svg" if size <= 32 else "photo-airt.svg"], size)

    # Linux: a hicolor icon theme, installed beside photo-airt.desktop.
    for size in (16, 24, 32, 48, 64, 128, 256, 512):
        out = HICOLOR / f"{size}x{size}" / "apps" / "photo-airt.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(pick(size))
    scalable = HICOLOR / "scalable" / "apps" / "photo-airt.svg"
    scalable.parent.mkdir(parents=True, exist_ok=True)
    scalable.write_text(sources["photo-airt.svg"])

    # Windows: embedded in photo-airt.exe by build.rs.
    (ICON / "photo-airt.ico").write_bytes(ico([(s, pick(s)) for s in (16, 20, 24, 32, 40, 48, 64, 128, 256)]))

    # macOS: the Photo-AIrt.app bundle icon.
    kinds = [(b"icp4", 16), (b"icp5", 32), (b"ic11", 32), (b"ic12", 64), (b"ic07", 128), (b"ic13", 256), (b"ic08", 256)]
    kinds += [(b"ic14", 512), (b"ic09", 512), (b"ic10", 1024)]
    (ICON / "photo-airt.icns").write_bytes(icns([(k, pick(s, macos=True)) for k, s in kinds]))
    print("Icon sources and rasters updated.")


if __name__ == "__main__":
    main()
